// Fill patterns. Each named character owns one main pattern; the build check enforces it.
// A pattern is a small tile drawn once and cached as a CanvasPattern.
// Tile functions draw in a 0..1 square; the helper repeats them so tiles join without seams.

const TAU = Math.PI * 2;

function helper(c, s) {
  return {
    d: (x, y, r = 0.08) => { c.beginPath(); c.arc(x * s, y * s, r * s, 0, TAU); c.fill(); },
    o: (x, y, r = 0.12) => { c.beginPath(); c.arc(x * s, y * s, r * s, 0, TAU); c.stroke(); },
    a: (x, y, r, a0, a1) => { c.beginPath(); c.arc(x * s, y * s, r * s, a0, a1); c.stroke(); },
    l: (...p) => { c.beginPath(); c.moveTo(p[0] * s, p[1] * s); for (let i = 2; i < p.length; i += 2) c.lineTo(p[i] * s, p[i + 1] * s); c.stroke(); },
    t: (...p) => { c.beginPath(); c.moveTo(p[0] * s, p[1] * s); for (let i = 2; i < p.length; i += 2) c.lineTo(p[i] * s, p[i + 1] * s); c.closePath(); c.fill(); },
    q: (x0, y0, cx, cy, x1, y1) => { c.beginPath(); c.moveTo(x0 * s, y0 * s); c.quadraticCurveTo(cx * s, cy * s, x1 * s, y1 * s); c.stroke(); },
  };
}

