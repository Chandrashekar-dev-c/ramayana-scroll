export const PATTERN_NAMES = Object.keys(TILES);

const cache = new Map();

/** A CanvasPattern for name, drawn with fg over bg. `k` scales the tile. */
export function pattern(ctx, name, bg, fg, k = 1) {
  // keyed on the whole-pixel tile size, not the raw scale: an enemy's float scale used to make a new
  // canvas for almost every value and the cache grew without end
  const def = TILES[name] || TILES.dots;
  const s = Math.max(4, Math.round(def[0] * k));
  const key = `${name}|${bg}|${fg}|${s}`;
  let p = cache.get(key);
  if (p) return p;
  const c = document.createElement('canvas');
  c.width = c.height = s;
  const x = c.getContext('2d');
  if (bg) { x.fillStyle = bg; x.fillRect(0, 0, s, s); }
  x.fillStyle = fg; x.strokeStyle = fg; x.lineWidth = Math.max(1, s * 0.07); x.lineCap = 'round'; x.lineJoin = 'round';
  const h = helper(x, s);
  for (let ox = -1; ox <= 1; ox++) for (let oy = -1; oy <= 1; oy++) {
    x.save(); x.translate(ox * s, oy * s); def[1](h); x.restore();
  }
  p = ctx.createPattern(c, 'repeat');
  cache.set(key, p);
  if (cache.size > 400) cache.delete(cache.keys().next().value);
  return p;
}

export function clearPatternCache() { cache.clear(); }
