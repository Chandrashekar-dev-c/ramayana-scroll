import { createRequire } from 'node:module';
const require = createRequire('/opt/npm-tools/node_modules/');
const { chromium, devices } = require('playwright');
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const ctx = await b.newContext({ ...devices['Pixel 5 landscape'] });
const p = await ctx.newPage();
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
const out = process.argv[2] || '.';
await p.goto('http://localhost:5173/');
await p.waitForFunction('window.__ready === true');
await p.waitForTimeout(800);
await p.screenshot({ path: out + '/phone-title.png' });
await p.evaluate(async () => { const R = window.__rs; R.save.data.difficulty = 'normal'; await R.start('tataka'); });
await p.waitForTimeout(6000);
await p.screenshot({ path: out + '/phone-battle.png' });
await p.evaluate(async () => { await window.__rs.start('boat'); });
await p.waitForTimeout(1500);
await p.screenshot({ path: out + '/phone-scene.png' });
const pctx = await b.newContext({ ...devices['Pixel 5'] });
const pp = await pctx.newPage(); await pp.goto('http://localhost:5173/'); await pp.waitForTimeout(2500); await pp.screenshot({ path: out + '/phone-portrait.png' });
console.log(errs.join('\n') || 'no errors');
await b.close();
